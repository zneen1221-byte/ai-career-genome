-- ============================================================
-- career.sql - 职业域建表 + 种子数据
-- 数据库：MySQL，字符集 utf8mb4
-- 对应 SPEC §6 FR-002/FR-003、§7
-- 幂等：可重复执行（TRUNCATE+INSERT 重置种子）
-- ============================================================

SET NAMES utf8mb4;

-- 题目表（20 道题）
CREATE TABLE IF NOT EXISTS questions (
  id          INT AUTO_INCREMENT PRIMARY KEY COMMENT '题目ID',
  title       VARCHAR(255) NOT NULL COMMENT '题目标题(短)',
  question    TEXT NOT NULL COMMENT '题目内容',
  option_a    VARCHAR(255) DEFAULT NULL COMMENT '选项A',
  option_b    VARCHAR(255) DEFAULT NULL COMMENT '选项B',
  option_c    VARCHAR(255) DEFAULT NULL COMMENT '选项C',
  option_d    VARCHAR(255) DEFAULT NULL COMMENT '选项D',
  score_rule  JSON DEFAULT NULL COMMENT '评分规则 {"A":{"C":2},...}',
  sort_order  INT DEFAULT 0 COMMENT '排序'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='题目表';

-- 职业类型表（6 种人格）
CREATE TABLE IF NOT EXISTS career_types (
  id               INT AUTO_INCREMENT PRIMARY KEY COMMENT '类型ID',
  type_code        VARCHAR(2) NOT NULL UNIQUE COMMENT '类型代码(C/S/I/B/M/E)',
  type_name        VARCHAR(32) NOT NULL COMMENT '类型名称',
  description      TEXT COMMENT '类型描述',
  strength         TEXT COMMENT '核心优势',
  career_direction TEXT COMMENT '职业方向'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业类型表';

-- 职业数据库
CREATE TABLE IF NOT EXISTS career_database (
  id               INT AUTO_INCREMENT PRIMARY KEY COMMENT '职业ID',
  traditional_job  VARCHAR(128) DEFAULT NULL COMMENT '传统职业',
  ai_risk          VARCHAR(32)  DEFAULT NULL COMMENT 'AI替代风险(低/中/高)',
  future_direction VARCHAR(255) DEFAULT NULL COMMENT '未来方向',
  skills           TEXT COMMENT '所需技能',
  income_model     VARCHAR(128) DEFAULT NULL COMMENT '收入模式'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='职业数据库';

